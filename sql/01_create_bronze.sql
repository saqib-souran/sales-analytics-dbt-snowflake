
-- Initial Snowflake setup for the ICOMMERCE project.
-- Run once before loading CSV files with Airflow.

CREATE DATABASE IF NOT EXISTS ICOMMERCE;

CREATE SCHEMA IF NOT EXISTS ICOMMERCE.BRONZE;
CREATE SCHEMA IF NOT EXISTS ICOMMERCE.SILVER;
CREATE SCHEMA IF NOT EXISTS ICOMMERCE.GOLD;

-- Keep raw source fields as VARCHAR.
-- Data cleaning and type conversion happen in dbt.

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.CATEGORY (
    CD_CATEGORY VARCHAR,
    LIB_CATEGORY VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.SUB_CATEGORY (
    CD_SUBCATEGORY VARCHAR,
    LIB_SUBCATEGORY VARCHAR,
    CD_CATEGORY VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.TYPE_CUSTOMER (
    CD_TYPE_CUSTOMER VARCHAR,
    LIB_TYPE_CUSTOMER VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.CUSTOMER (
    CUSTOMER_ID VARCHAR,
    LAST_NAME VARCHAR,
    FIRST_NAME VARCHAR,
    ADDRESS VARCHAR,
    POSTAL_CODE VARCHAR,
    CITY VARCHAR,
    COUNTRY VARCHAR,
    CD_TYPE_CUSTOMER VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.PRODUCT (
    CD_PRODUCT VARCHAR,
    LIB_PRODUCT VARCHAR,
    PRICE_PRODUCT VARCHAR,
    CD_SUBCATEGORY VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.SALE (
    SALE_ID VARCHAR,
    DT_SALE VARCHAR,
    CUSTOMER_ID VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS ICOMMERCE.BRONZE.DETAIL_SALE (
    SALE_ID VARCHAR,
    CD_PRODUCT VARCHAR,
    QUANTITY_SOLD VARCHAR,
    SALE_PRICE VARCHAR,
    SOURCE_SHA256 VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- Used by Airflow to stage CSV files for Snowflake COPY INTO.
CREATE STAGE IF NOT EXISTS
    ICOMMERCE.BRONZE.ICOMMERCE_CSV_STAGE;
